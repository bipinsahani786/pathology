                    ->where('is_package', true)
                    ->where(function ($q) use ($pkgSafeName) {
                        $q->where('name', $pkgSafeName)
                          ->orWhere(DB::raw('LOWER(TRIM(name))'), strtolower(trim($pkgSafeName)));
                    })
                    ->first();

                if ($existingPkg) {
                    $existingPkg->update([
                        'mrp' => $pkg['mrp'],
                        'b2b_price' => $pkg['b2b_price'],
                        'sample_type' => $pkgSafeSample,
                        'description' => 'Includes: ' . $pkg['included_tests'],
                        'is_active' => true,
                    ]);
                    $pkgUpdatedCount++;
                } else {
                    LabTest::create([
                        'company_id' => $company->id,
                        'name' => $pkgSafeName,
                        'test_code' => 'PKG_' . strtoupper(substr(preg_replace('/[^A-Za-z0-9]/', '', $pkgSafeName), 0, 10)),
                        'mrp' => $pkg['mrp'],
                        'b2b_price' => $pkg['b2b_price'],
                        'sample_type' => $pkgSafeSample,
                        'description' => 'Includes: ' . $pkg['included_tests'],
                        'is_package' => true,
                        'is_active' => true,
                    ]);
                    $pkgCreatedCount++;
                }
            }

            DB::commit();

            $this->command->info("Single Tests Processed: " . count($tests));
            $this->command->info(" -> Updated Existing Matches (Rates Synced): {$updatedCount}");
            $this->command->info(" -> Newly Created Tests: {$createdCount}");
            $this->command->info("Health Profiles / Packages Processed: " . count($packages));
            $this->command->info(" -> Packages Updated: {$pkgUpdatedCount}");
            $this->command->info(" -> Packages Newly Created: {$pkgCreatedCount}");
            $this->command->info("Done! All tests & packages successfully seeded for Lab [ID: {$company->id}] without duplicates.");

        } catch (\Throwable $e) {
            DB::rollBack();
            Log::error("AvWellcareLabTestsSeeder failed: " . $e->getMessage(), ['trace' => $e->getTraceAsString()]);
            $this->command->error("Seeder failed and transaction rolled back: " . $e->getMessage());
        }
    }
